// --- Video Reel Intersection Observer (Auto-play when visible) ---
const reelVideo = document.getElementById('promoReel');
const reelSection = document.querySelector('.video-reel-section');

if (reelVideo && reelSection) {
    const videoObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                // To allow autoplay with sound, most browsers require a user interaction first.
                // We start muted to ensure it plays, but user can click to unmute.
                reelVideo.muted = true;
                reelVideo.play().catch(err => console.log("Autoplay blocked:", err));

                // Show hint if browser allows
                const hint = document.querySelector('.reel-interaction-layer');
                if (hint) hint.classList.add('visible');
            } else {
                reelVideo.pause();
            }
        });
    }, { threshold: 0.5 });

    videoObserver.observe(reelSection);

    // Mute/Unmute Toggle on click
    const interactionLayer = document.querySelector('.reel-interaction-layer');
    if (interactionLayer) {
        interactionLayer.addEventListener('click', () => {
            reelVideo.muted = !reelVideo.muted;
            interactionLayer.classList.toggle('unmuted', !reelVideo.muted);

            // Hide hint after first interaction
            const muteHint = interactionLayer.querySelector('.mute-hint');
            if (muteHint) muteHint.style.display = 'none';
        });
    }
}

