function setLanguage(lang) {
    localStorage.setItem('sens_lang', lang);

    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translations[lang][key];
            } else {
                el.innerHTML = translations[lang][key];
            }
        }
    });

    // Update active class in switchers
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    // HTML lang attribute
    document.documentElement.lang = lang;
}

// Initial language setup
function getInitialLanguage() {
    const saved = localStorage.getItem('sens_lang');
    if (saved && ['es', 'en', 'pt'].includes(saved)) return saved;

    const languages = navigator.languages || [navigator.language];
    for (const lang of languages) {
        const short = lang.split('-')[0].toLowerCase();
        if (['es', 'en', 'pt'].includes(short)) return short;
    }
    return 'es';
}
const savedLang = getInitialLanguage();
window.addEventListener('DOMContentLoaded', () => {
    setLanguage(savedLang);

    // Lang switcher buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.stopPropagation(); // Avoid triggering parent listeners
            const lang = btn.getAttribute('data-lang');
            setLanguage(lang);
        });
    });
});

